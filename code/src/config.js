		droneGain: [0.07, 0.34],
		droneLowpass: 200,

		// 耳语：高 Q 带通噪声 + 慢扫频。最容易刺耳的层，增益压得很低
		//
		// 中心频率从 1800 收到 620 —— 这是被总输出低通"倒逼"的结果：
		// masterLPF 在低张力下是 2400，但 masterWall 固定 1100，
		// 而张力升高后 masterLPF 会一路降到 320。原来 1800 Hz 的中心
		// 在高张力下会被完全截断（实测这层的输出是 -Infinity dB，等于没声）。
		// 收到 620 Hz 并配 Q=3 后，它在全张力区间都留得住，
		// 而且"贴着耳朵说话"的频段本来就在 500–1500 Hz，更对。
	whisperGain: [0.0, 0.16],
	whisperStart: 0.45,
	whisperCenter: 620,
	whisperQ: 3,
	whisperLowpass: 1600,

	// ── 女鬼呼吸（本次新增：接近时的冷呼吸层）────────────
	// 【为什么不用玩家的呼吸参数】玩家呼吸是"自己的身体在报警"——
	// 快、浅、越怕越快（0.22→1.05 Hz）。女鬼的呼吸必须反着来：
	// 慢、深、而且**越近越慢**（0.21→0.13 Hz）。一件逼近你的东西
	// 呼吸却越来越沉，比"越来越急"错得更多 —— 错的就是恐怖的来源。
	// 频段也整体下移（中心 350 Hz，玩家在 520 Hz）："冷"在声学上
	// 就是更低的频段 + 拖得反常地长的呼气（见 GHOST_BREATH_CURVE）。
	// 增益由 setGhost(接近度 × 显形不透明度) 驱动，不进 setTension ——
