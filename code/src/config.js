	ghostBreathCenter: 350,
	ghostBreathQ: 1.4,
	ghostBreathLowpass: 640,
	ghostBreathRate: [0.21, 0.13], // Hz：远 → 近。越近越慢（与玩家呼吸相反）
	ghostBreathNear: 4.5, // 这个距离内呼吸满格（米）
	ghostBreathFar: 15, // 这个距离外呼吸消失（米）

		crackInterval: [75, 16], // 张力 0 → 1 的远处断裂间隔（秒）

		// ── 动物环境声（乌鸦 / 昆虫）──────────────────────────
		// 【间隔随张力拉长，与 crack 相反 —— 这不是笔误】
		// crack 是"危险的预兆"，越危险越频繁；
		// 鸟叫虫鸣是"安全的标记"，越危险越稀少。
		// 森林的安静本身就是恐怖的度量：玩家说不出为什么害怕，
		// 但他听得见鸟不叫了。这就是"静默是武器"的声学形态。
		//
		// 上限给得很长（乌鸦 150 s）：它必须稀有到"出现时你会真的去听"，
