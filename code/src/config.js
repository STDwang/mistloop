		// 总 RMS 会到 -18.3 dBFS（超出氛围音 -19 的上限），听感是"突然变吵"。
		// 收呼吸是因为它是三层里唯一的宽带噪声 —— 砍它最不容易伤到体感。
		breathGain: [0.0, 0.34],
		breathStart: 0.18, // 张力超过这个值呼吸才开始出现
		breathRate: [0.22, 1.05], // Hz
