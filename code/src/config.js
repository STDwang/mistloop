		// 冠层雨声的物理本质是一颗颗水滴砸在针叶上的**撞击**——
		// 它是有事件的，不是一片均匀的沙。连续层已经有 body/detail 两路，
		// 再铺一层高频连续噪声只会把 2–4 kHz 推向验收红线。
		// 离散滴答的占空比极低（每声 18–48 ms），对总频谱的均值几乎不动，
		// 但"淅淅沥沥"这个字面意思恰恰由它们读出来。
		// 每一响复用 oneShot 的 _burst（自带亮原料路由 + 4 kHz 低通护栏）。
		rainTickRate: [2.0, 9.0], // 每秒滴答数：天气 0 → 1（基线 0.3 的雨约 3.4/s）
		rainTickLevel: 0.028, // 单声峰值电平。比脚步碎裂（0.045–0.095）低一档
